) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='帖子收藏表';

CREATE TABLE report (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '举报ID',
    reporter_user_id BIGINT UNSIGNED NOT NULL COMMENT '举报用户ID',
    target_type VARCHAR(16) NOT NULL COMMENT '目标类型：POST、COMMENT',
    target_id BIGINT UNSIGNED NOT NULL COMMENT '举报目标ID',
    reason_type VARCHAR(32) NOT NULL COMMENT '举报原因类型',
    description VARCHAR(1000) NULL COMMENT '补充说明',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT '状态：PENDING、RESOLVED、REJECTED',
    handled_by_admin_id BIGINT UNSIGNED NULL COMMENT '处理后台账号ID',
    handle_note VARCHAR(1000) NULL COMMENT '处理备注',
    handled_at DATETIME(3) NULL COMMENT '处理时间',
    active_key VARCHAR(200) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS (CASE WHEN status = 'PENDING' THEN CONCAT(reporter_user_id, ':', target_type, ':', target_id) ELSE NULL END) STORED COMMENT '待处理举报唯一键',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_report_active_key (active_key),
    KEY idx_report_queue (status, created_at, id),
    KEY idx_report_target (target_type, target_id, status),
    KEY idx_report_user (reporter_user_id, created_at DESC, id DESC),
